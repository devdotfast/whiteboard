// Claude Code loads plugin/ as is, so the bundles are committed.
import { readFileSync, writeFileSync } from "node:fs";

const result = await Bun.build({
  entrypoints: ["src/register.tsx", "src/view.tsx"],
  outdir: "plugin/hooks",
  target: "browser",
  format: "esm",
  external: ["claude-code"],
  naming: "[name].js",
});
if (!result.success) {
  for (const log of result.logs) console.error(log);
  process.exit(1);
}
// Plugin tests can't read files, so the fixture becomes a module.
const fixture = readFileSync("../tui/test/fixtures/comparison.ndjson", "utf8");
writeFileSync("plugin/hooks/fixture.ts", `// Generated by build.ts from packages/tui/test/fixtures/comparison.ndjson.\nexport default ${JSON.stringify(fixture)};\n`);
for (const output of result.outputs) console.log(output.path);
